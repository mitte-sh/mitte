const (
	AuthDir       = "/etc/mitte/auth"
	ConfigFile    = AuthDir + "/configuration.yml"
	UsersFile     = AuthDir + "/users_database.yml"
	DataDir       = AuthDir + "/data"
	AutheliaImage = "authelia/authelia:latest"
	AutheliaPort  = "9091"
	ContainerName = "mitte-authelia"
)

// Config holds the Authelia configuration parameters.
type Config struct {
	JWTSecret     string
	SessionSecret string
	EncryptionKey string
	BaseDomain    string
	AutheliaURL   string // e.g. https://auth.example.com
	CookieDomain  string // e.g. .example.com
}

// EnsureAuthDir creates the auth config directory structure.
func EnsureAuthDir() error {
	if err := os.MkdirAll(AuthDir, 0755); err != nil {
		return fmt.Errorf("failed to create auth directory: %w", err)
	}
	if err := os.MkdirAll(DataDir, 0755); err != nil {
		return fmt.Errorf("failed to create auth data directory: %w", err)
	}
	return nil
}

// IsSetup returns true if Authelia has been configured.
func IsSetup() bool {
	_, err := os.Stat(ConfigFile)
	return err == nil
}

// GenerateConfig creates the Authelia configuration YAML.
func GenerateConfig(cfg Config) error {
	if err := EnsureAuthDir(); err != nil {
		return err
	}

	content := fmt.Sprintf(`# Mitte Authelia Configuration
# Generated by mitte auth setup — do not edit manually.

theme: auto

server:
  address: tcp://0.0.0.0:9091/

log:
  level: info

jwt_secret: %s

authentication_backend:
  file:
    path: /config/users_database.yml
    password:
      algorithm: argon2id
      argon2:
        variant: argon2id
        iterations: 3
        memory: 65536
        parallelism: 4
        key_length: 32
        salt_length: 16

session:
  name: mitte_auth_session
  secret: %s
  expiration: 3600
  inactivity: 300
  cookies:
    - domain: %s
      authelia_url: %s

storage:
  encryption_key: %s
  local:
    path: /config/db.sqlite3

access_control:
  default_policy: one_factor

notifier:
  filesystem:
    filename: /config/notification.txt
`, cfg.JWTSecret, cfg.SessionSecret, cfg.CookieDomain, cfg.AutheliaURL, cfg.EncryptionKey)

	if err := os.WriteFile(ConfigFile, []byte(content), 0644); err != nil {
		return fmt.Errorf("failed to write Authelia config: %w", err)
	}

	return nil
}

// GenerateUsersFile creates an empty users database file.
func GenerateUsersFile() error {
	if err := EnsureAuthDir(); err != nil {
		return err
	}

	content := `# Mitte Authelia Users Database
# Generated by mitte auth setup.
#
# Use 'mitte auth add-user <username>' to add users.
#
# Passwords are hashed with argon2id.
# Do not edit this file manually unless you know what you are doing.

users:
`
	if err := os.WriteFile(UsersFile, []byte(content), 0644); err != nil {
		return fmt.Errorf("failed to write users file: %w", err)
	}
	return nil
}

// UserEntry represents a user in the Authelia users database.
type UserEntry struct {
	Username    string
	DisplayName string
	Email       string
	Password    string // bcrypt hash
	Groups      []string
}

// AddUser adds a new user to the Authelia users database.
// The password should be provided in plain text; it will be hashed.
func AddUser(entry UserEntry, password string) error {
	if !IsSetup() {
		return fmt.Errorf("auth not configured. Run 'mitte auth setup' first")
	}

	hash, err := hashPassword(password)
	if err != nil {
		return fmt.Errorf("failed to hash password: %w", err)
	}

	// Read existing users file
	data, err := os.ReadFile(UsersFile)
	if err != nil {
		return fmt.Errorf("failed to read users file: %w", err)
	}

	// Check if user already exists
	if strings.Contains(string(data), fmt.Sprintf("  %s:", entry.Username)) {
		return fmt.Errorf("user '%s' already exists", entry.Username)
	}

	groups := strings.Join(entry.Groups, ", ")
	if groups == "" {
		groups = "users"
	}

	userBlock := fmt.Sprintf(`  %s:
    disabled: false
    displayname: "%s"
    password: "%s"
    email: %s
    groups:
      - %s
`, entry.Username, entry.DisplayName, hash, entry.Email, strings.Join(entry.Groups, "\n      - "))

	// Append to file
	f, err := os.OpenFile(UsersFile, os.O_APPEND|os.O_WRONLY, 0644)
	if err != nil {
		return fmt.Errorf("failed to open users file: %w", err)
	}
	defer f.Close()

	if _, err := f.WriteString(userBlock); err != nil {
		return fmt.Errorf("failed to write user entry: %w", err)
	}

	return nil
}

// RemoveUser removes a user from the Authelia users database.
func RemoveUser(username string) error {
	if !IsSetup() {
		return fmt.Errorf("auth not configured. Run 'mitte auth setup' first")
	}

	data, err := os.ReadFile(UsersFile)
	if err != nil {
		return fmt.Errorf("failed to read users file: %w", err)
	}

	lines := strings.Split(string(data), "\n")
	var result []string
	skip := false

	for _, line := range lines {
		trimmed := strings.TrimSpace(line)

		// Detect start of user block to remove
		if strings.HasPrefix(line, fmt.Sprintf("  %s:", username)) {
			skip = true
			continue
		}

		// Detect start of next user block (or non-indented line) to stop skipping
		if skip {
			if strings.HasPrefix(line, "  ") && !strings.HasPrefix(trimmed, "-") && strings.HasSuffix(trimmed, ":") && !strings.Contains(trimmed, " ") {
				skip = false
			} else if !strings.HasPrefix(line, "  ") && trimmed != "" {
				skip = false
			}
		}

		if !skip {
			result = append(result, line)
		}
	}

	if err := os.WriteFile(UsersFile, []byte(strings.Join(result, "\n")), 0644); err != nil {
		return fmt.Errorf("failed to write users file: %w", err)
	}

	return nil
}

// ListUsers parses the users database and returns user entries.
func ListUsers() ([]UserEntry, error) {
	if !IsSetup() {
		return nil, fmt.Errorf("auth not configured. Run 'mitte auth setup' first")
	}

	data, err := os.ReadFile(UsersFile)
	if err != nil {
		return nil, fmt.Errorf("failed to read users file: %w", err)
	}

	var users []UserEntry
	var current *UserEntry

	for _, line := range strings.Split(string(data), "\n") {
		trimmed := strings.TrimSpace(line)

		// User line: "  username:" (2 spaces indent, ends with colon, no spaces in the middle)
		if strings.HasPrefix(line, "  ") && strings.HasSuffix(trimmed, ":") && !strings.Contains(trimmed, " ") && len(trimmed) > 1 {
			if current != nil {
				users = append(users, *current)
			}
			username := strings.TrimSuffix(trimmed, ":")
			current = &UserEntry{Username: username}
			continue
		}

		if current == nil {
			continue
		}

		// Parse fields
		if strings.HasPrefix(trimmed, "displayname:") {
			current.DisplayName = strings.Trim(strings.TrimPrefix(trimmed, "displayname:"), ` "`)
		} else if strings.HasPrefix(trimmed, "email:") {
			current.Email = strings.TrimSpace(strings.TrimPrefix(trimmed, "email:"))
		} else if strings.HasPrefix(trimmed, "password:") {
			current.Password = strings.Trim(strings.TrimPrefix(trimmed, "password:"), ` "`)
		} else if strings.HasPrefix(trimmed, "- ") {
			current.Groups = append(current.Groups, strings.TrimPrefix(trimmed, "- "))
		}
	}

	if current != nil {
		users = append(users, *current)
	}

	return users, nil
}

// GenerateSecret generates a random secret string.
func GenerateSecret(length int) (string, error) {
	const chars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
	result := make([]byte, length)
	for i := range result {
		idx, err := rand.Int(rand.Reader, big.NewInt(int64(len(chars))))
		if err != nil {
			return "", err
		}
		result[i] = chars[idx.Int64()]
	}
	return string(result), nil
}

// hashPassword hashes a password using bcrypt.
func hashPassword(password string) (string, error) {
	hash, err := bcrypt.GenerateFromPassword([]byte(password), bcrypt.DefaultCost)
	if err != nil {
		return "", err
	}
	return string(hash), nil
}

