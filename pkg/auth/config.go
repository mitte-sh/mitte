// ACLRule represents a per-domain access control rule.
type ACLRule struct {
	Domain string
	Policy string // "one_factor" or "two_factor"
}

// GenerateConfigWithACL creates the Authelia configuration YAML with ACL rules.
func GenerateConfigWithACL(cfg Config, rules []ACLRule) error {
	if err := EnsureAuthDir(); err != nil {
		return err
	}

	var rulesYAML strings.Builder
	for _, rule := range rules {
		rulesYAML.WriteString(fmt.Sprintf("    - domain: %s\n      policy: %s\n", rule.Domain, rule.Policy))
	}

	content := fmt.Sprintf(`# Mitte Authelia Configuration
# Generated by mitte auth — do not edit manually.

theme: auto

server:
  address: tcp://0.0.0.0:9091/

log:
  level: info

jwt_secret: %s

authentication_backend:
  file:
    path: /config/users_database.yml
    password:
      algorithm: argon2id
      argon2:
        variant: argon2id
        iterations: 3
        memory: 65536
        parallelism: 4
        key_length: 32
        salt_length: 16

session:
  name: mitte_auth_session
  secret: %s
  expiration: 3600
  inactivity: 300
  cookies:
    - domain: %s
      authelia_url: %s

storage:
  encryption_key: %s
  local:
    path: /config/db.sqlite3

access_control:
  default_policy: one_factor
  rules:
%s
notifier:
  filesystem:
    filename: /config/notification.txt
`, cfg.JWTSecret, cfg.SessionSecret, cfg.CookieDomain, cfg.AutheliaURL, cfg.EncryptionKey, rulesYAML.String())

	if err := os.WriteFile(ConfigFile, []byte(content), 0644); err != nil {
		return fmt.Errorf("failed to write Authelia config: %w", err)
	}

	return nil
}

// LoadConfig reads the existing Authelia config and extracts secrets.
func LoadConfig() (*Config, error) {
	if !IsSetup() {
		return nil, fmt.Errorf("auth not configured. Run 'mitte auth setup' first")
	}

	data, err := os.ReadFile(ConfigFile)
	if err != nil {
		return nil, fmt.Errorf("failed to read config: %w", err)
	}

	content := string(data)

	cfg := &Config{}

	// Extract secrets by parsing lines
	for _, line := range strings.Split(content, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "jwt_secret:") {
			cfg.JWTSecret = strings.TrimSpace(strings.TrimPrefix(trimmed, "jwt_secret:"))
		} else if strings.HasPrefix(trimmed, "secret:") && cfg.SessionSecret == "" {
			cfg.SessionSecret = strings.TrimSpace(strings.TrimPrefix(trimmed, "secret:"))
		} else if strings.HasPrefix(trimmed, "encryption_key:") {
			cfg.EncryptionKey = strings.TrimSpace(strings.TrimPrefix(trimmed, "encryption_key:"))
		} else if strings.HasPrefix(trimmed, "- domain:") {
			// First domain in cookies is our cookie domain
			if cfg.CookieDomain == "" {
				cfg.CookieDomain = strings.TrimSpace(strings.TrimPrefix(trimmed, "- domain:"))
			}
		} else if strings.HasPrefix(trimmed, "authelia_url:") {
			cfg.AutheliaURL = strings.TrimSpace(strings.TrimPrefix(trimmed, "authelia_url:"))
		}
	}

	return cfg, nil
}

// CollectACLRules scans all app state files and returns ACL rules for protected apps.
func CollectACLRules() ([]ACLRule, error) {
	const appsDir = "/var/lib/mitte/apps"

	entries, err := os.ReadDir(appsDir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, fmt.Errorf("failed to read apps directory: %w", err)
	}

	var rules []ACLRule
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}

		data, err := os.ReadFile(appsDir + "/" + entry.Name())
		if err != nil {
			continue
		}

		// Minimal parsing to extract auth config and domains
		app, err := parseAppForACL(string(data))
		if err != nil || app == nil || app.Auth == nil || !app.Auth.Enabled {
			continue
		}

		for _, domain := range app.Domains {
			rules = append(rules, ACLRule{
				Domain: domain,
				Policy: app.Auth.Policy,
			})
		}
	}

	return rules, nil
}

// miniApp is a minimal struct for parsing app JSON for ACL rules.
type miniApp struct {
	Domains []string `json:"domains"`
	Auth    *struct {
		Enabled bool   `json:"enabled"`
		Policy  string `json:"policy"`
	} `json:"auth,omitempty"`
}

func parseAppForACL(jsonStr string) (*miniApp, error) {
	var app miniApp
	if err := jsonUnmarshalMinimal(jsonStr, &app); err != nil {
		return nil, err
	}
	return &app, nil
}

// jsonUnmarshalMinimal is a simple JSON parser for our miniApp struct.
func jsonUnmarshalMinimal(data string, app *miniApp) error {
	// Use encoding/json
	type alias miniApp
	var a alias
	if err := json.Unmarshal([]byte(data), &a); err != nil {
		return err
	}
	*app = miniApp(a)
	return nil
}
